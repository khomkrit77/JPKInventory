"""Generate a self-contained index.html that also opens directly via file://."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate():
    css = (ROOT / 'src/styles.css').read_text()
    parts = []
    for name in ['data.js', 'storage.js', 'app.js']:
        source = (ROOT / 'src' / name).read_text()
        source = re.sub(r'^import .*?;\s*', '', source, flags=re.MULTILINE)
        source = re.sub(r'^export ', '', source, flags=re.MULTILINE)
        parts.append(source)
    js = '\n'.join(parts).replace('</script', '<\\/script')
    html = '''<!doctype html>
<html lang="th">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="theme-color" content="#152c42">
<title>JPK Inventory | ระบบจัดการทรัพย์สินไอที</title>
<!-- Generated by scripts/make_preview.py; edit source files in src/. -->
<style>''' + css + '''</style>
</head>
<body>
<div id="app"></div>
<div id="toast" role="status" aria-live="polite"></div>
<dialog id="editor"></dialog>
<dialog id="confirmation"></dialog>
<script>
(() => {
'use strict';
''' + js + '''
})();
</script>
</body>
</html>
'''
    (ROOT / 'index.html').write_text(html)
    return html

if __name__ == '__main__':
    generate()
    print('Ready: index.html (open directly, no web server required)')
